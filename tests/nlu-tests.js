/* ============ اختبارات محرك الفهم اللغوي المحلي (NLU) ============ */
let nOk = 0, nBad = 0;
function T(name, cond) {
  if (cond) { nOk++; }
  else { nBad++; console.log('❌ ' + name); }
}

/* ---------- 1) الأرقام المنطوقة ---------- */
T('«الفين» → 2000', parseQuery('عايز سماعة بالفين جنيه').max === 2000 || parseQuery('سماعة الفين جنيه').max === 2000);
T('«خمس آلاف» → 5000', parseQuery('موبايل تحت خمس آلاف').max === 5000);
T('«تلاتة الاف» → 3000', parseQuery('سماعة بميزانية تلاتة الاف').max === 3000);
T('«15k» → 15000', parseQuery('موبايل تحت 15k').max === 15000);
T('«عشر آلاف» → 10000', parseQuery('حاجة للبيت تحت عشر آلاف').max === 10000);
T('أرقام عربية «١٥ الف»', parseQuery('موبايل تحت ١٥ الف').max === 15000);

/* ---------- 2) النطاق السعري ---------- */
{
  const p = parseQuery('موبايل بين 10000 و 20000');
  T('بين X و Y: min', p.min === 10000);
  T('بين X و Y: max', p.max === 20000);
}
{
  const p = parseQuery('سماعة من 1000 الى 3000');
  T('من X الى Y: min', p.min === 1000);
  T('من X الى Y: max', p.max === 3000);
}
{
  const p = parseQuery('موبايل بين 20000 و 10000');
  T('قلب النطاق المعكوس', p.min === 10000 && p.max === 20000);
}
{
  const p = parseQuery('سماعة حوالي 2000 جنيه');
  T('«حوالي 2000» → نطاق ±20%', p.min === 1600 && p.max === 2400);
  T('«حوالي 2000» لا تعني «قريب مني»', p.near === false);
}
T('«قريبة مني» ما زالت تعمل', parseQuery('سماعة قريبة مني').near === true);
T('«حواليا» تعني قريب مني', parseQuery('محلات موبايلات حواليا').near === true);

/* ---------- 3) تحمل الأخطاء الإملائية ---------- */
T('fuzzyEq: «سمسونج» ≈ «سامسونج»', fuzzyEq('سمسونج', 'سامسونج'));
T('fuzzyEq: «ايفوون» ≈ «ايفون»', fuzzyEq('ايفوون', 'ايفون'));
T('fuzzyEq: كلمات مختلفة لا تتطابق', !fuzzyEq('سماعه', 'مكنسه'));
T('ماركة بخطأ إملائي: «سمسونج»', parseQuery('موبايل سمسونج').brand === 'Samsung');
T('ماركة بالعربي: «شاومي»', parseQuery('موبايل شاومي رخيص').brand === 'Xiaomi');
{
  const p = parseQuery('عايز سماعا جي بي ال');
  T('فئة بخطأ إملائي: «سماعا» → صوتيات', !!(p.cat && p.cat.id === 'audio') || !!(p.product && p.product.cat === 'audio'));
}

/* ---------- 4) الجملة المركبة الكاملة ---------- */
{
  const p = parseQuery('عايز سماعة JBL تحت 3000 جنيه قريبة مني');
  T('الجملة المرجعية: فئة/منتج صوتيات', !!(p.product && p.product.cat === 'audio') || !!(p.cat && p.cat.id === 'audio'));
  T('الجملة المرجعية: ماركة JBL', p.brand === 'JBL');
  T('الجملة المرجعية: max=3000', p.max === 3000);
  T('الجملة المرجعية: قريب مني', p.near === true);
}
{
  const p = parseQuery('نفسي في موبايل سمسونج بين عشر آلاف و 20000 جنيه مفتوح دلوقتي');
  T('مركبة: ماركة بخطأ + نطاق منطوق + مفتوح الآن', p.brand === 'Samsung' && p.min === 10000 && p.max === 20000 && p.openNow === true);
}
{
  const r = searchListings('سماعة بين 1000 و 5000');
  T('البحث يطبق النطاق على النتائج', r.rows.every(x => x.price >= 1000 && x.price <= 5000));
}
T('استعلام فارغ لا يكسر المحرك', parseQuery('').unknown === true);
T('استعلام غير مفهوم', parseQuery('zzz qqq').unknown === true);

console.log('\n' + (nBad ? '⚠️ فشل ' + nBad + ' اختبارًا في محرك الفهم اللغوي (نجح ' + nOk + ')' : '🎉 كل اختبارات محرك الفهم اللغوي نجحت (' + nOk + ')'));
if (nBad) process.exitCode = 1;
